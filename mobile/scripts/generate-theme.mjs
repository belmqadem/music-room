// Generates the app's theme from the design tokens (DESIGN.md, ADR-029).
//
//   node scripts/generate-theme.mjs           write src/theme/*.generated.*
//   node scripts/generate-theme.mjs --check   fail if the files on disk are out of date
//
// Input:  ../design-tokens.json            the Stitch export, never edited by hand
//         ../design-tokens.extensions.json tokens we add (merged in; it may not override the export)
// Output: src/theme/tokens.generated.ts    colors, radii, type scale, font family names
//         src/theme/fonts.generated.ts     the font files to load, one import per weight
//         src/theme/theme.generated.css    the same values as Tailwind / NativeWind theme variables
//
// Pure TypeScript/JSON in, text out: `generateTheme` has no side effects so tests can call it.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HEADER =
  "GENERATED by mobile/scripts/generate-theme.mjs from design-tokens.json and design-tokens.extensions.json.\nDo not edit by hand: change the tokens and run `make theme`.";

// The name each color gets in code (camelCase) and in CSS (kebab-case, used as bg-*, text-*, border-*).
// Explicit on purpose: a token that is not listed here stops the build until someone names it.
const COLOR_NAMES = {
  "brand.electricEmber": "ember",
  "brand.electricEmberHover": "emberHover",
  "brand.chartreuse": "chartreuse",
  "surfaces.canvas": "canvas",
  "surfaces.surfaceContainerLowest": "surfaceLowest",
  "surfaces.surfaceContainerLow": "surfaceLow",
  "surfaces.surfaceElevated": "surfaceElevated",
  "surfaces.surfaceContainerHigh": "surfaceHigh",
  "surfaces.surfaceBright": "surfaceBright",
  "borders.subtle": "lineSubtle",
  "borders.focus": "lineFocus",
  "borders.liveSync": "lineLive",
  "text.primary": "contentPrimary",
  "text.secondary": "contentSecondary",
  "text.tertiary": "contentTertiary",
  "text.placeholder": "contentPlaceholder",
  "text.inverse": "contentInverse",
  "feedback.success": "success",
  "feedback.warning": "warning",
  "feedback.error": "error",
};

// expo-google-fonts names a weight like this: Syne_700Bold, PlusJakartaSans_600SemiBold.
const WEIGHT_NAMES = {
  400: "Regular",
  500: "Medium",
  600: "SemiBold",
  700: "Bold",
  800: "ExtraBold",
};

const COLOR_VALUE =
  /^(#[0-9A-Fa-f]{6}|rgba?\(\s*\d+\s*,\s*\d+\s*,\s*\d+\s*(,\s*[\d.]+\s*)?\))$/;

const kebab = (name) => name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const px = (value, what) => {
  const match = /^(-?\d+(\.\d+)?)px$/.exec(String(value));
  if (!match)
    throw new Error(`${what}: expected a size like "16px", got ${JSON.stringify(value)}`);
  return Number(match[1]);
};
const round2 = (n) => Math.round(n * 100) / 100;

/** Merges the extensions into the export. A token that already exists is an error, not an override. */
function mergeTokens(tokens, extensions) {
  const colors = structuredClone(tokens.colors);
  for (const [group, entries] of Object.entries(extensions?.colors ?? {})) {
    colors[group] ??= {};
    for (const [key, token] of Object.entries(entries)) {
      if (key in colors[group]) {
        throw new Error(
          `design-tokens.extensions.json: colors.${group}.${key} already exists in design-tokens.json`,
        );
      }
      colors[group][key] = token;
    }
  }
  return colors;
}

function buildColors(merged) {
  const colors = {};
  for (const [group, entries] of Object.entries(merged)) {
    for (const [key, token] of Object.entries(entries)) {
      const path = `${group}.${key}`;
      const name = COLOR_NAMES[path];
      if (!name) {
        throw new Error(
          `No theme name for color ${path}: add it to COLOR_NAMES in scripts/generate-theme.mjs`,
        );
      }
      if (!COLOR_VALUE.test(token.value)) {
        throw new Error(
          `colors.${path}: unsupported color ${JSON.stringify(token.value)} (use #RRGGBB or rgb()/rgba())`,
        );
      }
      colors[name] = token.value;
    }
  }
  return colors;
}

function buildFonts(typography) {
  const roles = {};
  for (const [role, family] of Object.entries(typography.fontFamilies)) {
    const name = family.value.split(",")[0].trim();
    const pascal = name.replace(/\s+/g, "");
    const loaded = {};
    for (const weight of family.weights) {
      const suffix = WEIGHT_NAMES[weight];
      if (!suffix)
        throw new Error(
          `fontFamilies.${role}: no name known for weight ${weight}; add it to WEIGHT_NAMES`,
        );
      loaded[weight] = `${pascal}_${weight}${suffix}`;
    }
    roles[role] = {
      pkg: `@expo-google-fonts/${name.toLowerCase().replace(/\s+/g, "-")}`,
      loaded,
    };
  }
  return roles;
}

/** Our text styles are added to the export's scale. A style that already exists is an error. */
function mergeScale(scale, extensions) {
  const merged = { ...scale };
  for (const [variant, style] of Object.entries(extensions?.typography?.scale ?? {})) {
    if (variant in merged) {
      throw new Error(
        `design-tokens.extensions.json: typography.scale.${variant} already exists in design-tokens.json`,
      );
    }
    merged[variant] = style;
  }
  return merged;
}

function buildTypography(scaleTokens, fonts) {
  const scale = {};
  for (const [variant, style] of Object.entries(scaleTokens)) {
    const role = fonts[style.fontFamily];
    if (!role)
      throw new Error(
        `scale.${variant}: unknown fontFamily ${JSON.stringify(style.fontFamily)}`,
      );
    const family = role.loaded[style.fontWeight];
    if (!family) {
      throw new Error(
        `scale.${variant}: ${style.fontFamily} has no weight ${style.fontWeight} in fontFamilies`,
      );
    }
    const fontSize = px(style.fontSize, `scale.${variant}.fontSize`);
    const spacing = /^(-?\d+(\.\d+)?)em$/.exec(style.letterSpacing ?? "0em");
    if (!spacing)
      throw new Error(`scale.${variant}.letterSpacing: expected a value like "-0.02em"`);
    scale[variant] = {
      fontFamily: family,
      fontSize,
      lineHeight: px(style.lineHeight, `scale.${variant}.lineHeight`),
      // React Native wants pixels; the tokens say em.
      letterSpacing: round2(Number(spacing[1]) * fontSize),
      ...(style.textTransform ? { textTransform: style.textTransform } : {}),
    };
  }
  return scale;
}

function buildRadius(borderRadius) {
  return Object.fromEntries(
    Object.entries(borderRadius).map(([name, value]) => [
      name,
      px(value, `borderRadius.${name}`),
    ]),
  );
}

/** Our maximum widths (extensions only: the export has none), in pixels. */
function buildMaxWidth(maxWidth = {}) {
  return Object.fromEntries(
    Object.entries(maxWidth).map(([name, token]) => [
      name,
      px(token.value, `maxWidth.${name}`),
    ]),
  );
}

const q = (key) => (/^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key));
const lines = (entries, indent) => entries.map((line) => `${indent}${line}`).join("\n");

function tsFile(theme) {
  const colorLines = Object.entries(theme.colors).map(
    ([k, v]) => `${q(k)}: ${JSON.stringify(v)},`,
  );
  const radiusLines = Object.entries(theme.radius).map(([k, v]) => `${q(k)}: ${v},`);
  const maxWidthLines = Object.entries(theme.maxWidth).map(([k, v]) => `${q(k)}: ${v},`);
  const familyLines = Object.entries(theme.fonts).flatMap(([role, { loaded }]) => [
    `${q(role)}: {`,
    ...Object.entries(loaded).map(
      ([weight, family]) => `  ${q(weight)}: ${JSON.stringify(family)},`,
    ),
    "},",
  ]);
  const scaleLines = Object.entries(theme.typography).flatMap(([variant, s]) => [
    `${q(variant)}: {`,
    `  fontFamily: ${JSON.stringify(s.fontFamily)},`,
    `  fontSize: ${s.fontSize},`,
    `  lineHeight: ${s.lineHeight},`,
    `  letterSpacing: ${s.letterSpacing},`,
    ...(s.textTransform ? [`  textTransform: ${JSON.stringify(s.textTransform)},`] : []),
    "},",
  ]);
  return `/* ${HEADER.split("\n").join("\n   ")} */

export const colorMode = ${JSON.stringify(theme.colorMode)} as const;

export const colors = {
${lines(colorLines, "  ")}
} as const;

/** Corner radii in pixels. */
export const radius = {
${lines(radiusLines, "  ")}
} as const;

/** Maximum widths in pixels (className: max-w-<name>). */
export const maxWidth = {
${lines(maxWidthLines, "  ")}
} as const;

/** The name React Native knows each loaded font file by: fontFamilies[role][weight]. */
export const fontFamilies = {
${lines(familyLines, "  ")}
} as const;

/** What a text style needs. letterSpacing is in pixels (the tokens say em). */
export interface TypographyStyle {
  readonly fontFamily: string;
  readonly fontSize: number;
  readonly lineHeight: number;
  readonly letterSpacing: number;
  readonly textTransform?: "uppercase";
}

export const typography = {
${lines(scaleLines, "  ")}
} as const satisfies Record<string, TypographyStyle>;

export type ColorName = keyof typeof colors;
export type RadiusName = keyof typeof radius;
export type TypographyVariant = keyof typeof typography;
`;
}

function fontsFile(theme) {
  const imports = [];
  const names = [];
  for (const { pkg, loaded } of Object.values(theme.fonts)) {
    for (const [weight, family] of Object.entries(loaded)) {
      // One import per weight, from its own folder, so only the weights we use are bundled.
      imports.push(
        `import { ${family} } from "${pkg}/${weight}${WEIGHT_NAMES[weight]}";`,
      );
      names.push(family);
    }
  }
  return `/* ${HEADER.split("\n").join("\n   ")} */

${imports.join("\n")}

/** Pass to expo-font's useFonts: every weight the tokens declare, each loaded explicitly. */
export const fontAssets = {
${lines(
  names.map((n) => `${n},`),
  "  ",
)}
};
`;
}

function cssFile(theme) {
  const out = [];
  out.push("/* " + HEADER.split("\n").join("\n   ") + " */");
  out.push("@theme {");
  out.push(
    "  /* Start from nothing: only the design tokens exist, so bg-red-500 and friends do not. */",
  );
  out.push("  --color-*: initial;");
  for (const [name, value] of Object.entries(theme.colors))
    out.push(`  --color-${kebab(name)}: ${value};`);
  out.push("");
  out.push("  --radius-*: initial;");
  for (const [name, value] of Object.entries(theme.radius))
    out.push(`  --radius-${name}: ${value}px;`);
  out.push("");
  out.push(
    "  /* max-w-<name>: Tailwind takes max widths from the --container namespace. */",
  );
  out.push("  --container-*: initial;");
  for (const [name, value] of Object.entries(theme.maxWidth))
    out.push(`  --container-${name}: ${value}px;`);
  out.push("");
  out.push(
    "  /* font-<role>-<weight>: the loaded font file for that weight (React Native cannot synthesize weights). */",
  );
  out.push("  --font-*: initial;");
  for (const [role, { loaded }] of Object.entries(theme.fonts)) {
    for (const [weight, family] of Object.entries(loaded))
      out.push(`  --font-${role}-${weight}: ${family};`);
  }
  out.push("");
  out.push("  --text-*: initial;");
  for (const [variant, s] of Object.entries(theme.typography)) {
    out.push(`  --text-${kebab(variant)}: ${s.fontSize}px;`);
    out.push(`  --text-${kebab(variant)}--line-height: ${s.lineHeight}px;`);
    out.push(`  --text-${kebab(variant)}--letter-spacing: ${s.letterSpacing}px;`);
  }
  out.push("}");
  return out.join("\n") + "\n";
}

/** @returns {{ colorMode: string, colors: object, radius: object, maxWidth: object, fonts: object, typography: object, files: Record<string, string> }} */
export function generateTheme(tokens, extensions = {}) {
  if (tokens.colorMode !== "dark")
    throw new Error(
      `colorMode: only "dark" is supported, got ${JSON.stringify(tokens.colorMode)}`,
    );
  const fonts = buildFonts(tokens.typography);
  const theme = {
    colorMode: tokens.colorMode,
    colors: buildColors(mergeTokens(tokens, extensions)),
    radius: buildRadius(tokens.borderRadius),
    maxWidth: buildMaxWidth(extensions.maxWidth),
    fonts,
    typography: buildTypography(mergeScale(tokens.typography.scale, extensions), fonts),
  };
  return {
    ...theme,
    files: {
      "tokens.generated.ts": tsFile(theme),
      "fonts.generated.ts": fontsFile(theme),
      "theme.generated.css": cssFile(theme),
    },
  };
}

// ---- command line ----
const here = dirname(fileURLToPath(import.meta.url));
const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];

if (isMain) {
  const root = join(here, "..", "..");
  const outDir = join(here, "..", "src", "theme");
  const read = (file) => JSON.parse(readFileSync(join(root, file), "utf8"));
  const { files } = generateTheme(
    read("design-tokens.json"),
    read("design-tokens.extensions.json"),
  );
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const [name, content] of Object.entries(files)) {
    const path = join(outDir, name);
    let current = null;
    try {
      current = readFileSync(path, "utf8");
    } catch {
      /* not generated yet */
    }
    if (current === content) continue;
    if (check) {
      console.error(`${name} is out of date. Run \`make theme\`.`);
      stale++;
    } else {
      writeFileSync(path, content);
      console.log(`wrote src/theme/${name}`);
    }
  }
  if (stale > 0) process.exit(1);
  if (check) console.log("theme is up to date");
}
